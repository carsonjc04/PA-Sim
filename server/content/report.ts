const label = (list: { id: string; label: string }[], id: string) => list.find((x) => x.id === id)?.label ?? id
const esc = (s: string) => s.replace(/\|/g, '\\|')
const list = (items: string[]) => (items.length ? items.map(esc).join(', ') : '-')

const DISCLAIMER =
  'This report lists which tags the authored cases carry. **It is not a measure of coverage of the NCCPA PANCE blueprint or of any end-of-rotation blueprint.** The tags are author-proposed and unreviewed, and five cases cannot represent a blueprint.'

function pivot(title: string, scenarios: ScenarioDefinition[], vocab: { id: string; label: string }[], pick: (s: ScenarioDefinition) => string[]): string {
  const rows = vocab.map((v) => {
    const hits = scenarios.filter((s) => pick(s).includes(v.id)).map((s) => s.id)
    return `| ${esc(v.label)} | ${hits.length} | ${hits.length ? hits.join(', ') : '**none**'} |`
  })
  return `### ${title}\n\n| Category | Cases | Which |\n| --- | ---: | --- |\n${rows.join('\n')}\n`
}

/** Deterministic: no clock, so a committed copy can be compared byte for byte. */
export function coverageMarkdown(pkg: LoadedContent): string {
  const { scenarios, taxonomy: v, manifest } = pkg
  const rows = scenarios.map((s) => {
    const t = s.taxonomy
    return `| ${s.id} | ${list(t.organSystems.map((x) => label(v.organSystems, x)))} | ${list(t.panceTasks.map((x) => label(v.panceTasks, x)))} | ${label(v.careSettings, t.careSetting)} | ${t.acuity} | ${label(v.ageGroups, t.ageGroup)} | ${list(t.eorRotations.map((x) => label(v.eorRotations, x)))} |`
  })
  return [
    '# Content coverage report',
    '',
    '<!-- Generated by `npm run content:coverage`. Do not edit by hand. -->',
    '',
    `> ${DISCLAIMER}`,
    '',
    `Package version ${manifest.manifestVersion}, ${scenarios.length} scenarios. Tag provenance: ${[...new Set(scenarios.map((s) => s.taxonomy.provenance))].join(', ')}.`,
    '',
    '## Scenarios',
    '',
    '| Scenario | Organ system | PANCE task | Care setting | Acuity | Age group | EOR rotation |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    '## Counts by tag',
    '',
    pivot('Organ system', scenarios, v.organSystems, (s) => s.taxonomy.organSystems),
    pivot('PANCE task', scenarios, v.panceTasks, (s) => s.taxonomy.panceTasks),
    pivot('Care setting', scenarios, v.careSettings, (s) => [s.taxonomy.careSetting]),
    pivot('Acuity', scenarios, [{ id: 'routine', label: 'Routine' }, { id: 'urgent', label: 'Urgent' }, { id: 'emergent', label: 'Emergent' }], (s) => [s.taxonomy.acuity]),
    pivot('Patient age group', scenarios, v.ageGroups, (s) => [s.taxonomy.ageGroup]),
    pivot('EOR rotation tag', scenarios, v.eorRotations, (s) => s.taxonomy.eorRotations),
    `Vocabulary source: ${v.provenance}`,
    '',
  ].join('\n')
}

export function statusMarkdown(pkg: LoadedContent): string {
  const published = new Map(pkg.manifest.scenarios.map((e) => [e.id, e.published]))
  const rows = pkg.scenarios.map((s) => {
    const l = s.lifecycle
    const reviews = l.reviews.length ? l.reviews.map((r) => `${r.reviewerRole} ${r.reviewedAt} (${r.outcome}, v${r.contentVersion})`).join('; ') : 'none'
    const refs = s.clinicalReferences.filter((r) => !r.verified).length
    const sources = `${s.clinicalReferences.length} (${refs} unverified, ${s.clinicalReferences.some((r) => r.specificity === 'case-specific') ? 'has case-specific' : 'general only'})`
    return `| ${s.id} | ${l.status} | ${l.contentVersion} | ${published.get(s.id) ? 'yes' : 'no'} | ${esc(reviews)} | ${l.nextReviewDue} | ${sources} | ${s.criticalWaivers.length} |`
  })
  const open = pkg.scenarios.flatMap((s) => s.lifecycle.openItems.map((i) => `- **${s.id}**: ${i}`))
  return [
    '# Content status',
    '',
    '<!-- Generated by `npm run content:coverage`. Do not edit by hand. -->',
    '',
    '> Maintainer view. **No case is approved unless a qualified reviewer (PA-C, MD, DO, NP or PharmD) has recorded an approving review of that exact version in a pull request.** Learners see only the label "Requires clinician review". Review records hold a role and a date, never a name.',
    '',
    `Package version ${pkg.manifest.manifestVersion}, grading ${pkg.manifest.gradingVersion}.`,
    '',
    '| Scenario | Status | Version | Published | Reviews | Next review due | References | Critical waivers |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    '## Open items',
    '',
    ...(open.length ? open : ['None.']),
    '',
    '## Content fingerprints',
    '',
    'Locked in `content/lock.json`. A changed fingerprint at an unchanged version fails validation.',
    '',
    ...pkg.scenarios.map((s) => `- ${s.id}@${s.lifecycle.contentVersion}: \`${contentFingerprint(s).slice(0, 16)}\``),
    '',
  ].join('\n')
}

export function lockFor(pkg: LoadedContent, existing: ContentLock): ContentLock {
  const releases = [...existing.releases]
  for (const s of pkg.scenarios) {
    if (!releases.some((r) => r.id === s.id && r.contentVersion === s.lifecycle.contentVersion)) {
      releases.push({ id: s.id, contentVersion: s.lifecycle.contentVersion, fingerprint: contentFingerprint(s) })
    }
  }
  releases.sort((a, b) => (a.id === b.id ? a.contentVersion.localeCompare(b.contentVersion, undefined, { numeric: true }) : a.id.localeCompare(b.id)))
  return { lockVersion: 1, releases }
}

